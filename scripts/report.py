#!/usr/bin/env python
"""Regenerate the run-log table in an experiment's report, and the global INDEX.

The table is generated from ``runs.jsonl``; everything you write around it is
preserved. Only the region between the RUNS markers is replaced, so your
interpretation is never clobbered by a regeneration.

    python scripts/report.py 003-backbone-comparison
    python scripts/report.py 003-backbone-comparison --metric recall@1
    python scripts/report.py --index
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from uavloc.builds import list_builds, open_blocks  # noqa: E402
from uavloc.datasets import list_datasets  # noqa: E402
from uavloc.track import EXPERIMENTS, load_runs  # noqa: E402

BEGIN = "<!-- RUNS:BEGIN — generated by scripts/report.py, do not edit by hand -->"
END = "<!-- RUNS:END -->"


def _is_scalar(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


LOWER_IS_BETTER = ("error", "loss")


def _best(metric: str, vals: list[float]) -> float:
    """Errors and losses are best when smallest; everything else when largest."""
    return min(vals) if any(word in metric for word in LOWER_IS_BETTER) else max(vals)


def _primary_metric(runs: list[dict]) -> str | None:
    for r in runs:
        for k, v in r.get("metrics", {}).items():
            if _is_scalar(v):
                return k
    return None


def _fmt_changed(run: dict) -> str:
    changed = run.get("changed") or {}
    if not changed:
        return "*baseline*" if run["run"].endswith(".1") else "—"
    return "<br>".join(
        f"`{k}: {v['from']} → {v['to']}`" for k, v in changed.items()
    )


def _flags(run: dict, prev: dict | None = None) -> str:
    """Reasons a run's delta may not mean what it appears to mean."""
    out = []
    if run.get("status") != "ok":
        out.append("❌ failed")
    if run.get("code_changed"):
        out.append("⚠ code changed")
    if run.get("code_hash") is None:
        out.append("⚠ code unverified")
    if len(run.get("changed") or {}) > 1:
        out.append(f"⚠ {len(run['changed'])} vars")

    # Device is not part of `config`, so a device switch shows an empty diff
    # while moving the metric. Without this the row reads as a free win.
    dev = (run.get("env") or {}).get("device")
    prev_dev = (prev.get("env") or {}).get("device") if prev else None
    if prev_dev and dev and prev_dev != dev:
        out.append(f"⚠ device {prev_dev}→{dev}, not comparable")

    if (run.get("git") or {}).get("dirty"):
        out.append("⚠ dirty tree")
    return " ".join(out)


def run_table(exp: str, metric: str | None = None) -> str:
    runs = load_runs(exp)
    if not runs:
        return f"{BEGIN}\n\n*No runs recorded yet.*\n\n{END}"

    metric = metric or _primary_metric(runs)
    lines = [
        BEGIN,
        "",
        f"| Run | Changed vs. prev | {metric or 'result'} | Δ | Note | Flags |",
        "|---|---|---|---|---|---|",
    ]

    prev_val = None
    prev_run = None
    for r in runs:
        val = r.get("metrics", {}).get(metric) if metric else None
        if _is_scalar(val):
            cell = f"{val:.4g}"
            if _is_scalar(prev_val):
                d = val - prev_val
                delta = f"{d:+.4g}"
            else:
                delta = "—"
            prev_val = val
        else:
            cell, delta = "—", "—"

        lines.append(
            f"| `{r['run']}` | {_fmt_changed(r)} | {cell} | {delta} "
            f"| {r.get('note', '')} | {_flags(r, prev_run)} |"
        )
        prev_run = r

    ok = [r for r in runs if r.get("status") == "ok"]
    lines += ["", f"*{len(runs)} run(s), {len(ok)} completed. "
                  f"Generated from `runs.jsonl`.*", "", END]
    return "\n".join(lines)


def write_report(exp: str, metric: str | None = None) -> Path:
    d = EXPERIMENTS / exp
    report = d / "report.md"
    table = run_table(exp, metric)

    if report.exists():
        text = report.read_text()
        if BEGIN in text and END in text:
            head, rest = text.split(BEGIN, 1)
            _, tail = rest.split(END, 1)
            text = head + table + tail
        else:
            text = text.rstrip() + "\n\n## Run log\n\n" + table + "\n"
    else:
        text = (f"# {exp} — report\n\n"
                f"> Interpretation is written by hand. The table below is "
                f"generated.\n\n## Run log\n\n{table}\n\n"
                f"## What we learned\n\n_TBD_\n\n## Next\n\n_TBD_\n")

    report.write_text(text)
    return report


def write_index() -> Path:
    exps = sorted(
        p.name for p in EXPERIMENTS.iterdir()
        if p.is_dir() and not p.name.startswith("_")
    )
    lines = [
        "# Experiment index",
        "",
        "> Generated by `scripts/report.py --index`. Experiments ask "
        "questions; datasets are equipment they run on.",
        "",
        "## Experiments",
        "",
        "| Experiment | Runs | Status | Best | Metric | Last run |",
        "|---|---|---|---|---|---|",
    ]
    for e in exps:
        runs = load_runs(e)
        if not runs:
            lines.append(f"| [`{e}`]({e}/proposal.md) | 0 | planned | — | — | — |")
            continue
        metric = _primary_metric(runs)
        vals = [r["metrics"][metric] for r in runs
                if r.get("status") == "ok" and _is_scalar(r.get("metrics", {}).get(metric))]
        best = f"{_best(metric, vals):.4g}" if vals else "—"
        last = runs[-1]["timestamp"][:10]
        status = "active" if any(r.get("status") == "ok" for r in runs) else "failing"
        lines.append(
            f"| [`{e}`]({e}/report.md) | {len(runs)} | {status} | {best} "
            f"| `{metric or '—'}` | {last} |"
        )

    lines += ["", "## Datasets", "",
              "> Equipment, not experiments — no bar to miss. `checks` is the "
              "evidence that lets a null result be blamed on the idea rather "
              "than the data.", "",
              "| Dataset | Ver | Samples | Size | Ref | Checks |",
              "|---|---|---|---|---|---|"]
    ds = list_datasets()
    if not ds:
        lines.append("| *none registered* | — | — | — | — | — |")
    for m in ds:
        n = m["name"]
        if m.get("unbuilt"):
            lines.append(f"| [`{n}`](../datasets/{n}/card.md) | — | — | — "
                         f"| *not built* | — |")
            continue
        size = f"{m['bytes'] / 1e6:.0f} MB" if m["bytes"] < 1e9 else f"{m['bytes'] / 1e9:.1f} GB"
        checks = ", ".join(f"{k}: {v}" for k, v in (m.get("checks") or {}).items()) or "⚠ none"
        lines.append(
            f"| [`{n}`](../datasets/{n}/card.md) | {m['version']} "
            f"| {m.get('samples') or m['n_files']} | {size} "
            f"| `{n}@{m['hash'][:6]}` | {checks} |"
        )

    lines += ["", "## Builds", "",
              "> Reusable work and its evidence. `notes.md` in each folder is "
              "the source of truth — this table parses it.", "",
              "| Build | Status | Unblocks | Waiting on you |",
              "|---|---|---|---|"]
    builds = list_builds()
    if not builds:
        lines.append("| *none* | — | — | — |")
    for b in builds:
        pending = [n for n in b["needs"] if not n["done"]]
        # An input that exists but is still unticked means the user delivered
        # and nobody noticed. Surface it as a call to action, not a block.
        wait = ", ".join(
            ("**arrived** " if n["exists"] else "") + (n["path"] or n["what"])
            for n in pending
        ) or "—"
        lines.append(
            f"| [`{b['name']}`](../builds/{b['name']}/notes.md) | {b['status']} "
            f"| {', '.join(f'`{u}`' for u in b['unblocks']) or '—'} | {wait} |"
        )

    blocks = open_blocks()
    if blocks["arrived"]:
        lines += ["", "**Inputs that have arrived and are not yet ticked off:**", ""]
        lines += [f"- `{r['build']}` — {r['what']} → `{r['path']}`"
                  for r in blocks["arrived"]]

    f = EXPERIMENTS / "INDEX.md"
    f.write_text("\n".join(lines) + "\n")
    return f


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("exp", nargs="?", help="experiment slug")
    ap.add_argument("--metric", help="primary metric column")
    ap.add_argument("--index", action="store_true", help="regenerate INDEX.md only")
    a = ap.parse_args()

    if a.exp:
        print(f"wrote {write_report(a.exp, a.metric)}")
    print(f"wrote {write_index()}")


if __name__ == "__main__":
    main()
